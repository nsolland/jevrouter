import { strict as assert } from "node:assert";
import { test } from "node:test";
import { routePairwise } from "../src/routing/routellm-pairwise.js";
const valid = { strongModel:"strong", weakModel:"weak", strongWinRate:0.8, threshold:0.5, calibrationId:"cohort-v1", allowedModels:["strong","weak"] };
test("strong route remains decision-only",()=>{ const r=routePairwise(valid);assert.equal(r.choice,"strong");assert.equal(r.requiresAuthorization,true); });
test("weak route at threshold",()=>assert.equal(routePairwise({...valid,strongWinRate:0.5}).choice,"weak"));
test("missing calibration abstains",()=>assert.equal(routePairwise({...valid,calibrationId:null}).choice,"abstain"));
test("invalid score abstains",()=>assert.equal(routePairwise({...valid,strongWinRate:NaN}).choice,"abstain"));
test("forbidden model abstains",()=>assert.equal(routePairwise({...valid,allowedModels:["strong"]}).choice,"abstain"));
test("invalid threshold abstains",()=>assert.equal(routePairwise({...valid,threshold:2}).choice,"abstain"));
